func writeReturnMsgError(_ w: IndentWriter, rt: Routine, isUser: Bool, errorCode: String) {
  w.writeln("\t\t{ ")
  if isUser {
    if !rtMessOnStack(rt) {
      w.writeln("\t\tmig_user_deallocate((char *) Mess, (mach_msg_size_t)sizeof(*Mess));")
    }
    w.writeln("\t\treturn \(errorCode); }")
  } else {
    w.writeln("\t\t{ MIG_RETURN_ERROR(OutP, \(errorCode)); }")
  }
}
