import Foundation

// MARK: - Output file helpers

class IndentWriter {
  let stream: FileHandle
  var indentLevel = 0

  init(stream: FileHandle) {
    self.stream = stream
  }

  func write(_ s: String) {
    let indented = String(repeating: "\t", count: indentLevel) + s
    stream.write(Data(indented.utf8))
  }

  func writeln(_ s: String = "") {
    write(s + "\n")
  }

  func indent() { indentLevel += 1 }
  func outdent() { indentLevel = max(0, indentLevel - 1) }

  func blankLine() { writeln() }
}

// MARK: - File open helpers

func openWriteHandle(_ name: String) -> FileHandle? {
  if name.isEmpty || name == "/dev/null" { return nil }
  let url = URL(fileURLWithPath: name)

  if !FileManager.default.fileExists(atPath: name) {
    _ = FileManager.default.createFile(atPath: name, contents: nil)
  }

  return try? FileHandle(forWritingTo: url)
}

func openIndentWriter(_ name: String) -> IndentWriter? {
  if name.isEmpty || name == "/dev/null" { return nil }
  guard let handle = FileHandle(forWritingAtPath: name) else {
    // Try creating
    _ = FileManager.default.createFile(atPath: name, contents: nil)
    guard let h = FileHandle(forWritingAtPath: name) else {
      fatal("openOutputFile: cannot write to \(name)")
    }
    return IndentWriter(stream: h)
  }
  handle.truncateFile(atOffset: 0)
  return IndentWriter(stream: handle)
}

func writeFile(_ name: String, content: String) {
  do {
    try content.write(toFile: name, atomically: true, encoding: .utf8)
  } catch {
    fatal("Cannot write to \(name): \(error)")
  }
}

// MARK: - Writer functions

func writeIdentificationString(_ w: IndentWriter) {
  w.writeln("/*")
  w.writeln(" * IDENTIFICATION:")
  w.writeln(" * stub generated by \(Global.MIG_VERSION)")
  w.writeln(" * OPTIONS: ")
  if Global.isKernelUser { w.writeln(" *\tKernelUser") }
  if Global.isKernelServer { w.writeln(" *\tKernelServer") }
  if !Global.useMsgRPC { w.writeln(" *\t-R (no RPC calls)") }
  w.writeln(" */")
}

func writeBogusDefines(_ w: IndentWriter) {
  w.writeln("#ifndef\tmig_internal")
  w.writeln("#define\tmig_internal\tstatic __inline__")
  w.writeln("#endif\t/* mig_internal */")
  w.blankLine()
  w.writeln("#ifndef\tmig_external")
  w.writeln("#define mig_external")
  w.writeln("#endif\t/* mig_external */")
  w.blankLine()
  w.writeln("#if\t!defined(__MigTypeCheck) && defined(TypeCheck)")
  w.writeln("#define\t__MigTypeCheck\t\tTypeCheck\t/* Legacy setting */")
  w.writeln("#endif\t/* !defined(__MigTypeCheck) */")
  w.blankLine()
  w.writeln("#if\t!defined(__MigKernelSpecificCode) && defined(_MIG_KERNEL_SPECIFIC_CODE_)")
  w.writeln("#define\t__MigKernelSpecificCode\t_MIG_KERNEL_SPECIFIC_CODE_\t/* Legacy setting */")
  w.writeln("#endif\t/* !defined(__MigKernelSpecificCode) */")
  w.blankLine()
  w.writeln("#ifndef\tLimitCheck")
  w.writeln("#define\tLimitCheck 0")
  w.writeln("#endif\t/* LimitCheck */")
  w.blankLine()
  w.writeln("#ifndef\tmin")
  w.writeln("#define\tmin(a,b)  ( ((a) < (b))? (a): (b) )")
  w.writeln("#endif\t/* min */")
  w.blankLine()

  let align = Int(itWordAlign)
  w.writeln("#if !defined(_WALIGN_)")
  w.writeln("#define _WALIGN_(x) (((x) + \(align - 1)) & ~\(align - 1))")
  w.writeln("#endif /* !defined(_WALIGN_) */")
  w.blankLine()
  w.writeln("#if !defined(_WALIGNSZ_)")
  w.writeln("#define _WALIGNSZ_(x) _WALIGN_(sizeof(x))")
  w.writeln("#endif /* !defined(_WALIGNSZ_) */")
  w.blankLine()
  w.writeln("#ifndef\tUseStaticTemplates")
  if Global.beAnsiC {
    w.writeln("#define\tUseStaticTemplates\t0")
  } else {
    w.writeln("#if\t\(Global.newCDecl)")
    w.writeln("#define\tUseStaticTemplates\t0")
    w.writeln("#endif\t/* \(Global.newCDecl) */")
  }
  w.writeln("#endif\t/* UseStaticTemplates */")
  w.blankLine()
}

func writeImport(_ w: IndentWriter, filename: String) {
  w.writeln("#include \(filename)")
}

func writeImplImports(_ w: IndentWriter, statements: [Statement], isUser: Bool) {
  for st in statements {
    switch st.stKind {
    case .import_, .iImport:
      writeImport(w, filename: st.stFileName)
    case .sImport:
      if !isUser {
        writeImport(w, filename: st.stFileName)
      }
    case .uImport:
      if isUser {
        writeImport(w, filename: st.stFileName)
      }
    case .routine, .dImport:
      break
    default: break
    }
  }
}

func writeRCSDecl(_ w: IndentWriter, name: String, rcs: String) {
  let const = Global.beAnsiC ? "const " : ""
  w.writeln("#ifndef\tlint")
  w.writeln("#if\tUseExternRCSId")
  w.writeln("\(const)char \(name)_rcsid[] = \(rcs);")
  w.writeln("#else\t/* UseExternRCSId */")
  w.writeln("static \(const)char rcsid[] = \(rcs);")
  w.writeln("#endif\t/* UseExternRCSId */")
  w.writeln("#endif\t/* lint */")
  w.blankLine()
}

