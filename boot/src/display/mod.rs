pub fn draw_char(px: usize, py: usize, c: u8, fg: u32, bg: u32) {
    let fb = get_info();
    if !fb.active || fb.addr == 0 || px + 8 > fb.width || py + 16 > fb.height {
        return;
    }

    let glyph_idx = if c >= 32 && c <= 126 {
        (c - 32) as usize
    } else {
        0
    };

    let glyph_bytes = &FONT_8X16[glyph_idx * 16..(glyph_idx + 1) * 16];

    for row in 0..16 {
        let bits = glyph_bytes[row];
        let y = py + row;
        for col in 0..8 {
            let x = px + col;
            let on = (bits & (0x80 >> col)) != 0;
            let color = if on { fg } else { bg };

            if !on && (bg & 0xff00_0000) != 0 {
                continue;
            }

            match fb.format {
                PixelFormat::Rgb565 => {
                    let r = ((color >> 16) & 0xff) as u8;
                    let g = ((color >> 8) & 0xff) as u8;
                    let b = (color & 0xff) as u8;
                    let c16 = rgb565(r, g, b);
                    let ptr = (fb.addr + y * fb.stride + x * 2) as *mut u16;
                    unsafe {
                        core::ptr::write_volatile(ptr, c16);
                    }
                }
                PixelFormat::Xrgb8888 | PixelFormat::Argb8888 | PixelFormat::Unknown(_) => {
                    let ptr = (fb.addr + y * fb.stride + x * 4) as *mut u32;
                    unsafe {
                        core::ptr::write_volatile(ptr, color);
                    }
                }
            }
        }
    }

    clean_dcache_range(fb.addr + py * fb.stride, 16 * fb.stride);
}

pub fn print(s: &str) {
    let fb = get_info();
    if !fb.active || fb.addr == 0 {
        return;
    }

    let mut con = CONSOLE.lock();
    for byte in s.bytes() {
        if byte == b'\n' {
            con.cursor_x = 8;
            con.cursor_y += 18;
            if con.cursor_y + 16 >= fb.height {
                con.cursor_y = 8;
            }
            continue;
        }

        draw_char(con.cursor_x, con.cursor_y, byte, con.fg_color, con.bg_color);
        con.cursor_x += 9;
        if con.cursor_x + 8 >= fb.width {
            con.cursor_x = 8;
            con.cursor_y += 18;
            if con.cursor_y + 16 >= fb.height {
                con.cursor_y = 8;
            }
        }
    }
}

pub fn println(s: &str) {
    print(s);
    print("\n");
}

pub fn print_panic(msg: &str) {
    panic_paint();
    let mut con = CONSOLE.lock();
    con.cursor_x = 16;
    con.cursor_y = 32;
    con.fg_color = 0x00ff_ffff;
    con.bg_color = 0x00ff_0000;
    drop(con);

    println("========================================");
    println("        KERNEL PANIC / EXCEPTION        ");
    println("========================================");
    println(msg);
}
