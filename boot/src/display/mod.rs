//! Early display beacon, visual progress reporter, and screen console.
//!
//! On headless or sealed hardware (such as the Spotify Car Thing / Superbird,
//! Amlogic Meson G12A, or Pixel 7a / gs201) where UART test pads are
//! unreachable or unwired, the display panel is the primary debug and
//! status channel.
//!
//! Supports:
//! 1. Direct hardware adoption of the active bootloader-programmed scanout
//!    buffer (RGB565 / XRGB8888 / ARGB8888) - see the board submodules
//!    below for the actual register reads, which differ per SoC.
//! 2. Immediate liveness painting before and after MMU is enabled.
//! 3. Color stage beacons (orange for boot, blue for DTB, purple for IOKit, gradient for running).
//! 4. Panic & exception painting (bright solid RED on panic or fatal exception).
//! 5. Framebuffer text rendering via a built-in 8x16 bitmap font.
//!
//! This module holds everything board-agnostic: the framebuffer/console
//! state, pixel-format-aware drawing primitives, and the font. Each board
//! gets its own submodule containing only the hardware-specific bit -
//! "how do I find the buffer the bootloader already lit up, and where is
//! it" - selected at compile time by Cargo/Bazel `crate_features` (see
//! `boards.bzl`), mirroring the `qemu` feature split used elsewhere
//! (`board.rs`, `lib.rs`).

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use spin::Mutex;

#[cfg(feature = "gs201")]
mod gs201;
#[cfg(feature = "gs201")]
use gs201 as chip;

#[cfg(not(feature = "gs201"))]
mod amlogic;
#[cfg(not(feature = "gs201"))]
use amlogic as chip;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum PixelFormat {
    #[default]
    Rgb565,
    Xrgb8888,
    Argb8888,
    Unknown(u32),
}

#[derive(Debug, Clone, Copy, Default)]
pub struct FramebufferInfo {
    pub addr: usize,
    pub stride: usize,
    pub width: usize,
    pub height: usize,
    pub format: PixelFormat,
    pub active: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BootStage {
    /// Early bootstrap entry (Orange)
    Bootstrap,
    /// Memory & PMM initialized (Yellow)
    MemoryReady,
    /// DeviceTree & GIC initialized (Cyan)
    DeviceTreeReady,
    /// IPC, IOKit & Drivers matched (Magenta / Purple)
    IokitReady,
    /// Userland spawned / Scheduler running (Green / Gradient)
    Running,
    /// Kernel panic or unhandled exception (Red)
    Panic,
}

struct ConsoleState {
    cursor_x: usize,
    cursor_y: usize,
    fg_color: u32,
    bg_color: u32,
}

static FB_INFO: Mutex<FramebufferInfo> = Mutex::new(FramebufferInfo {
    addr: 0,
    stride: 0,
    width: 0,
    height: 0,
    format: PixelFormat::Rgb565,
    active: false,
});

static CONSOLE: Mutex<ConsoleState> = Mutex::new(ConsoleState {
    cursor_x: 8,
    cursor_y: 8,
    fg_color: 0x00ff_ffff,
    bg_color: 0x0000_0000,
});

static IS_PRESENT: AtomicBool = AtomicBool::new(false);
static ADOPTED_ADDR: AtomicUsize = AtomicUsize::new(0);

pub fn is_present() -> bool {
    IS_PRESENT.load(Ordering::Acquire)
}

#[inline]
pub(crate) unsafe fn read32(addr: usize) -> u32 {
    unsafe { core::ptr::read_volatile(addr as *const u32) }
}

#[inline]
pub(crate) unsafe fn write32(addr: usize, val: u32) {
    unsafe { core::ptr::write_volatile(addr as *mut u32, val) };
}

/// Cleans data cache for the specified memory range to ensure non-coherent display DMA observes it.
pub fn clean_dcache_range(addr: usize, len: usize) {
    const LINE: usize = 64;
    let start = addr & !(LINE - 1);
    let end = (addr + len + LINE - 1) & !(LINE - 1);
    let mut line = start;
    while line < end {
        unsafe {
            core::arch::asm!("dc cvac, {0}", in(reg) line, options(nostack));
        }
        line += LINE;
    }
    unsafe {
        core::arch::asm!("dsb sy", options(nomem, nostack));
    }
}

pub const fn rgb565(r: u8, g: u8, b: u8) -> u16 {
    (((r as u16) >> 3) << 11) | (((g as u16) >> 2) << 5) | ((b as u16) >> 3)
}

pub const fn xrgb8888(r: u8, g: u8, b: u8) -> u32 {
    ((r as u32) << 16) | ((g as u32) << 8) | (b as u32)
}

/// Adopts the bootloader-programmed framebuffer, if one was found live and
/// enabled, as this hv's own console/beacon surface. Delegates the actual
/// register reads to the active board submodule (`chip::read_hardware_fb`).
pub fn init_early() -> bool {
    if let Some(info) = chip::read_hardware_fb() {
        {
            let mut fb = FB_INFO.lock();
            *fb = info;
        }
        IS_PRESENT.store(true, Ordering::Release);
        ADOPTED_ADDR.store(info.addr, Ordering::Release);

        // Immediate visual feedback on physical screen
        paint_gradient();
        true
    } else {
        false
    }
}

pub fn early_marker() {
    paint(255, 140, 0);
}

pub fn configure_manual(
    addr: usize,
    stride: usize,
    width: usize,
    height: usize,
    format: PixelFormat,
) {
    let mut fb = FB_INFO.lock();
    fb.addr = addr;
    fb.stride = stride;
    fb.width = width;
    fb.height = height;
    fb.format = format;
    fb.active = true;

    IS_PRESENT.store(true, Ordering::Release);
    ADOPTED_ADDR.store(addr, Ordering::Release);
}

pub fn is_active() -> bool {
    IS_PRESENT.load(Ordering::Acquire)
}

pub fn get_info() -> FramebufferInfo {
    let fb = *FB_INFO.lock();
    if fb.active {
        fb
    } else {
        chip::read_hardware_fb().unwrap_or(fb)
    }
}

pub fn paint(r: u8, g: u8, b: u8) {
    let fb = get_info();
    if !fb.active || fb.addr == 0 || fb.width == 0 || fb.height == 0 {
        return;
    }

    match fb.format {
        PixelFormat::Rgb565 => {
            let color = rgb565(r, g, b);
            for y in 0..fb.height {
                let row_ptr = (fb.addr + y * fb.stride) as *mut u16;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
        }
        PixelFormat::Xrgb8888 | PixelFormat::Argb8888 | PixelFormat::Unknown(_) => {
            let color = xrgb8888(r, g, b);
            for y in 0..fb.height {
                let row_ptr = (fb.addr + y * fb.stride) as *mut u32;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
        }
    }

    clean_dcache_range(fb.addr, fb.height * fb.stride);
    chip::kick_scanout();
}

pub fn paint_gradient() {
    let fb = get_info();
    if !fb.active || fb.addr == 0 || fb.width == 0 || fb.height == 0 {
        return;
    }

    for y in 0..fb.height {
        let t = (y * 255 / fb.height.max(1)) as u8;
        let r = t;
        let g = 64;
        let b = 255 - t;

        match fb.format {
            PixelFormat::Rgb565 => {
                let color = rgb565(r, g, b);
                let row_ptr = (fb.addr + y * fb.stride) as *mut u16;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
            PixelFormat::Xrgb8888 | PixelFormat::Argb8888 | PixelFormat::Unknown(_) => {
                let color = xrgb8888(r, g, b);
                let row_ptr = (fb.addr + y * fb.stride) as *mut u32;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
        }
    }

    clean_dcache_range(fb.addr, fb.height * fb.stride);
    chip::kick_scanout();
}

pub fn panic_paint() {
    paint(255, 0, 0);
}

pub fn mark_stage(stage: BootStage) {
    match stage {
        BootStage::Bootstrap => {
            paint_gradient();
        }
        BootStage::MemoryReady => {
            draw_status_bar(240, 200, 20, 12);
        }
        BootStage::DeviceTreeReady => {
            draw_status_bar(0, 180, 240, 12);
        }
        BootStage::IokitReady => {
            draw_status_bar(180, 50, 220, 12);
        }
        BootStage::Running => {
            draw_status_bar(0, 220, 80, 12);
        }
        BootStage::Panic => {
            panic_paint();
        }
    }
}

/// Draws a thin full-width boot-stage indicator strip at the *bottom* of
/// the panel - not the top: the console (`print`/`println`) always starts
/// writing at the top, so a top-anchored bar would cover the very boot log
/// text this beacon exists alongside.
pub fn draw_status_bar(r: u8, g: u8, b: u8, bar_height: usize) {
    let fb = get_info();
    if !fb.active || fb.addr == 0 || fb.width == 0 || fb.height == 0 {
        return;
    }

    let h = bar_height.min(fb.height);
    let y0 = fb.height - h;
    for y in y0..fb.height {
        match fb.format {
            PixelFormat::Rgb565 => {
                let color = rgb565(r, g, b);
                let row_ptr = (fb.addr + y * fb.stride) as *mut u16;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
            PixelFormat::Xrgb8888 | PixelFormat::Argb8888 | PixelFormat::Unknown(_) => {
                let color = xrgb8888(r, g, b);
                let row_ptr = (fb.addr + y * fb.stride) as *mut u32;
                for x in 0..fb.width {
                    unsafe {
                        core::ptr::write_volatile(row_ptr.add(x), color);
                    }
                }
            }
        }
    }

    clean_dcache_range(fb.addr + y0 * fb.stride, h * fb.stride);
}

